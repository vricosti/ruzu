const fn xtime(x: u8) -> u8 {
    (x << 1) ^ (((x >> 7) & 1) * 0x1b)
}

const fn multiply(x: u8, y: u8) -> u8 {
    ((y & 1) * x)
        ^ (((y >> 1) & 1) * xtime(x))
        ^ (((y >> 2) & 1) * xtime(xtime(x)))
        ^ (((y >> 3) & 1) * xtime(xtime(xtime(x))))
        ^ (((y >> 4) & 1) * xtime(xtime(xtime(xtime(x)))))
}

fn shift_rows(out_state: &mut State, state: &State) {
    out_state[0] = state[0];
    out_state[4] = state[4];
    out_state[8] = state[8];
    out_state[12] = state[12];
    out_state[1] = state[5];
    out_state[5] = state[9];
    out_state[9] = state[13];
    out_state[13] = state[1];
    out_state[2] = state[10];
    out_state[10] = state[2];
    out_state[6] = state[14];
    out_state[14] = state[6];
    out_state[3] = state[15];
    out_state[15] = state[11];
    out_state[11] = state[7];
    out_state[7] = state[3];
}

fn inverse_shift_rows(out_state: &mut State, state: &State) {
    out_state[0] = state[0];
    out_state[4] = state[4];
    out_state[8] = state[8];
    out_state[12] = state[12];
    out_state[13] = state[9];
    out_state[9] = state[5];
    out_state[5] = state[1];
    out_state[1] = state[13];
    out_state[2] = state[10];
    out_state[10] = state[2];
    out_state[6] = state[14];
    out_state[14] = state[6];
    out_state[3] = state[7];
    out_state[7] = state[11];
    out_state[11] = state[15];
    out_state[15] = state[3];
}

fn sub_bytes(state: &mut State, table: &[u8; 256]) {
    for byte in state {
        *byte = table[*byte as usize];
    }
}

pub extern "C" fn decrypt_single_round(out_state: &mut State, state: &State) {
    inverse_shift_rows(out_state, state);
    sub_bytes(out_state, &INVERSE_SUBSTITUTION_BOX);
}

pub extern "C" fn encrypt_single_round(out_state: &mut State, state: &State) {
    shift_rows(out_state, state);
    sub_bytes(out_state, &SUBSTITUTION_BOX);
}

pub extern "C" fn mix_columns(out_state: &mut State, state: &State) {
    for i in (0..out_state.len()).step_by(4) {
        let (a, b, c, d) = (state[i], state[i + 1], state[i + 2], state[i + 3]);
        let tmp = a ^ b ^ c ^ d;
        out_state[i] = a ^ xtime(a ^ b) ^ tmp;
        out_state[i + 1] = b ^ xtime(b ^ c) ^ tmp;
        out_state[i + 2] = c ^ xtime(c ^ d) ^ tmp;
        out_state[i + 3] = d ^ xtime(d ^ a) ^ tmp;
    }
}

pub extern "C" fn inverse_mix_columns(out_state: &mut State, state: &State) {
    for i in (0..out_state.len()).step_by(4) {
        let (a, b, c, d) = (state[i], state[i + 1], state[i + 2], state[i + 3]);
        out_state[i] =
            multiply(a, 0x0e) ^ multiply(b, 0x0b) ^ multiply(c, 0x0d) ^ multiply(d, 0x09);
        out_state[i + 1] =
            multiply(a, 0x09) ^ multiply(b, 0x0e) ^ multiply(c, 0x0b) ^ multiply(d, 0x0d);
        out_state[i + 2] =
            multiply(a, 0x0d) ^ multiply(b, 0x09) ^ multiply(c, 0x0e) ^ multiply(d, 0x0b);
        out_state[i + 3] =
            multiply(a, 0x0b) ^ multiply(b, 0x0d) ^ multiply(c, 0x09) ^ multiply(d, 0x0e);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fips_197_round_transformations() {
        let input = [
            0x19, 0x3d, 0xe3, 0xbe, 0xa0, 0xf4, 0xe2, 0x2b, 0x9a, 0xc6, 0x8d, 0x2a, 0xe9, 0xf8,
            0x48, 0x08,
        ];
        let mut shifted_and_substituted = [0; 16];
        encrypt_single_round(&mut shifted_and_substituted, &input);
        assert_eq!(
            shifted_and_substituted,
            [
                0xd4, 0xbf, 0x5d, 0x30, 0xe0, 0xb4, 0x52, 0xae, 0xb8, 0x41, 0x11, 0xf1, 0x1e, 0x27,
                0x98, 0xe5,
            ]
        );

        let mut mixed = [0; 16];
        mix_columns(&mut mixed, &shifted_and_substituted);
        assert_eq!(
            mixed,
            [
                0x04, 0x66, 0x81, 0xe5, 0xe0, 0xcb, 0x19, 0x9a, 0x48, 0xf8, 0xd3, 0x7a, 0x28, 0x06,
                0x26, 0x4c,
            ]
        );
    }

    #[test]
    fn inverse_transformations_are_exact_inverses() {
        let input = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        let mut encrypted = [0; 16];
        encrypt_single_round(&mut encrypted, &input);
        let mut decrypted = [0; 16];
        decrypt_single_round(&mut decrypted, &encrypted);
        assert_eq!(decrypted, input);

        let mut mixed = [0; 16];
        mix_columns(&mut mixed, &input);
        let mut unmixed = [0; 16];
        inverse_mix_columns(&mut unmixed, &mixed);
        assert_eq!(unmixed, input);
    }
}
